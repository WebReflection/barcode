#!/usr/bin/env python3
"""Generate crates/barcode-fixtures/src/oracle_matrices.rs — frozen zint
oracle renders used as fixture specimens (show.html / e2e / harden).

Test tooling only. These are NOT encoders: they are a small keyed bank of
valid 2-D matrices so the display rig can render specimens for symbologies
whose encoder half was never written (DM/Aztec/PDF417). Extend BANK by
adding payloads here and re-running:

    /tmp/opencode/zxenv/bin/python tools/gen_oracle_matrices.py

Polarity: every helper is normalized to 1 = inked before emitting
(dmtx/pdf417 native 1=ink; aztec svg native 0=ink -> inverted).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from dmtx_oracle import encode_matrix as dm_matrix
from aztec_probe import encode_matrix as az_matrix
from pdf417_probe import pdf417_matrix

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates/barcode-fixtures/src/oracle_matrices.rs"


def to_pattern(matrix):
    """rows of 0/1 (1=ink) -> '#'/'.', newline-joined."""
    return "\n".join("".join("#" if v == 1 else "." for v in row) for row in matrix)


def dm_rect_opt2():
    """Probe zint DMRE size indices; first landscape that fits the payload."""
    for opt2 in range(25, 31):
        try:
            m, r, c = dm_matrix("DM-RECT-01", opt2=opt2)
        except RuntimeError:
            continue  # payload too long for this size
        if c > r:
            return opt2, (r, c)
    raise SystemExit("no landscape DMRE fits")


def main():
    rect_opt2, rect_rc = dm_rect_opt2()
    print(f"DM landscape DMRE index {rect_opt2} -> {rect_rc[0]}x{rect_rc[1]}")

    bank = []  # (symbology, text, matrix)

    # --- DataMatrix -------------------------------------------------
    for text, kw in [
        ("DM-PHYS-001", {}),
        ("DM-RECT-001", {"opt2": rect_opt2}),
        ("DM-BIG-001", {"opt2": 4}),  # explicit 16x16 square
        ("DATA MATRIX LONGER PAYLOAD 42", {}),
    ]:
        m, r, c = dm_matrix(text, **kw)
        bank.append(("datamatrix", text, m, f"dmtx_oracle.encode_matrix({text!r}, **{kw})"))
        print(f"datamatrix {text!r}: {r}x{c}")

    # --- Aztec (svg path: 0=ink native -> invert) --------------------
    for text, kw in [
        ("AZTEC-PHYS-001", {}),
        ("AZTEC-PHYS-002", {"option_2": 2}),
        ("https://example.com/aztec", {}),
    ]:
        m, r, c = az_matrix(text, **kw)
        m = [[1 - v for v in row] for row in m]
        bank.append(("aztec", text, m, f"aztec_probe.encode_matrix({text!r}, **{kw})"))
        print(f"aztec {text!r}: {r}x{c}")

    # --- PDF417 (10 module-rows per codeword band, 1 px/module) ------
    for text, kw in [
        ("PDF417-PHYS-001", {}),
        ("PDF417-PHYS-002", {"cols": 3}),
        ("PDF417 LONGER PAYLOAD 0123456789", {}),
    ]:
        m, r, c = pdf417_matrix(text, **kw)
        bank.append(("pdf417", text, m, f"pdf417_probe.pdf417_matrix({text!r}, **{kw})"))
        print(f"pdf417 {text!r}: {r}x{c}")

    # --- emit --------------------------------------------------------
    entries = []
    for sym, text, m, recipe in bank:
        pat = to_pattern(m).replace('"', '\\"')
        rows, cols = len(m), len(m[0])
        assert all(len(row) == cols for row in m)
        entries.append(
            f'    ("{sym}", "{text}", OracleMatrix {{ rows: {rows}, cols: {cols}, '
            f'pattern: "{pat}" }}), // {recipe}'
        )

    OUT.write_text(
        "//! GENERATED by tools/gen_oracle_matrices.py — frozen zint oracle\n"
        "//! renders, used as fixture SPECIMENS for symbologies whose encoder\n"
        "//! half was never written (datamatrix / aztec / pdf417). Same role as\n"
        "//! the frozen matrices in the decoder crates' golden tests: test\n"
        "//! inputs only, NOT encoders. '#' = inked module, '.' = light.\n"
        "//! Regenerate: /tmp/opencode/zxenv/bin/python tools/gen_oracle_matrices.py\n"
        "\n"
        "/// One frozen specimen: row-major `#`/`.` pattern, `rows` lines of `cols`.\n"
        "#[derive(Debug, Clone, Copy)]\n"
        "pub struct OracleMatrix {\n"
        "    pub rows: u32,\n"
        "    pub cols: u32,\n"
        "    pub pattern: &'static str,\n"
        "}\n"
        "\n"
        "/// Keyed bank: (symbology, text) -> specimen.\n"
        "const BANK: &[(&str, &str, OracleMatrix)] = &[\n"
        + "\n".join(entries)
        + "\n];\n"
        "\n"
        "/// Look up a frozen specimen. Returns `None` for payloads not in the\n"
        "/// bank — add those via the generator (see module docs).\n"
        "pub fn oracle_matrix(symbology: &str, text: &str) -> Option<OracleMatrix> {\n"
        "    BANK.iter()\n"
        "        .find(|(s, t, _)| *s == symbology && *t == text)\n"
        "        .map(|(_, _, m)| *m)\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(bank)} specimens)")


if __name__ == "__main__":
    main()
