"""Generate crates/barcode-pdf417/src/text_tables.rs from the verified
probe TABLE3 (spec Table 3, visually read + oracle-verified).

Also emits tests/golden.rs data constants (frozen zint matrices) from
the oracle BMPs -- nothing passes through human retyping.
"""

import json
import sys

sys.path.insert(0, "/Users/ag/git/barcode/tools")
from pdf417_text_probe import TABLE3  # noqa: E402

OUT_TEXT = "/Users/ag/git/barcode/crates/barcode-pdf417/src/text_tables.rs"

MNEMONIC_NAME = {"ll": "Ll", "ml": "Ml", "ps": "Ps", "as": "As", "al": "Al", "pl": "Pl"}
SUB_NAMES = ["ALPHA", "LOWER", "MIXED", "PUNCT"]


def gen_tables():
    lines = [
        "//! Text compaction sub-mode tables (spec Table 3). GENERATED by",
        "//! tools/pdf417_gen_tables.py from the verified probe constants --",
        "//! do not edit by hand.",
        "",
        "/// One Table-3 cell: a data character or a sub-mode switch.",
        "#[derive(Clone, Copy, PartialEq, Eq, Debug)]",
        "pub enum Cell {",
        "    /// ASCII character (GLI 0).",
        "    Ch(u8),",
        "    Ll, Ml, Ps, As, Al, Pl,",
        "}",
        "",
        "/// Sub-modes: 0 Alpha, 1 Lower, 2 Mixed, 3 Punct (spec order).",
        f"pub static TEXT_TABLES: [[Cell; 30]; 4] = [",
    ]
    for name in SUB_NAMES:
        name_l = name.lower()
        rows = []
        for v in range(30):
            cell = TABLE3[name_l][v]
            if isinstance(cell, str):
                rows.append(f"Cell::{MNEMONIC_NAME[cell]}")
            else:
                rows.append(f"Cell::Ch({cell})")
        lines.append(f"    // {name}")
        lines.append("    [" + ", ".join(rows) + "],")
    lines.append("];")
    lines.append("")
    lines.append("/// Sub-mode names indexed as TEXT_TABLES.")
    lines.append("pub const ALPHA: usize = 0;")
    lines.append("pub const LOWER: usize = 1;")
    lines.append("pub const MIXED: usize = 2;")
    lines.append("pub const PUNCT: usize = 3;")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    open(OUT_TEXT, "w").write(gen_tables())
    print("wrote", OUT_TEXT)
