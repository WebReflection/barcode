def corrupt_specs(full, k, cap, seed):
    """Deterministic corruption at `cap` positions; returns (pos, delta)."""
    import random
    rng = random.Random(seed)
    positions = sorted(rng.sample(range(len(full)), cap))
    return [(p, rng.randrange(1, 929)) for p in positions]

RS_TMPL = """
use barcode_pdf417::rs::{k_for_level, rs_encode, rs_valid};

/// (payload, level, message, ecc) -- GENERATED from zint oracle streams.
/// message = descriptor + data + pads (row indicators excluded);
/// ecc = complement of the RS remainder, spec 2.6.3.
const RS_VECTORS: &[(&str, u8, &[u16], &[u16])] = &[
@RVECTORS@
];

#[test]
fn rs_encoder_matches_oracle() {
    for (payload, level, message, ecc) in RS_VECTORS {
        let k = k_for_level(*level);
        assert_eq!(k, ecc.len(), "{:?} k", payload);
        assert_eq!(&rs_encode(message, k), ecc, "{:?} ecc", payload);
    }
}

#[test]
fn rs_validates_oracle_streams() {
    for (payload, level, message, ecc) in RS_VECTORS {
        let mut full = message.to_vec();
        full.extend_from_slice(ecc);
        assert!(rs_valid(&full, k_for_level(*level)), "{:?} valid", payload);
    }
}

#[test]
fn rs_rejects_corruption() {
    for (payload, level, message, ecc) in RS_VECTORS {
        let mut full = message.to_vec();
        full.extend_from_slice(ecc);
        // corrupt one data codeword and one ecc codeword
        full[1] = (full[1] + 1) % 929;
        assert!(!rs_valid(&full, k_for_level(*level)), "{:?} data corrupt", payload);
        let mut full2 = message.to_vec();
        full2.extend_from_slice(ecc);
        let last = full2.len() - 1;
        full2[last] = (full2[last] + 1) % 929;
        assert!(!rs_valid(&full2, k_for_level(*level)), "{:?} ecc corrupt", payload);
    }
}

/// (payload, level, full stream, [(pos, delta)] applied to corrupt) --
/// GENERATED; correction must restore the original exactly.
const RS_CORRUPTIONS: &[(&str, u8, &[u16], &[(usize, u16)])] = &[
@RCORRUPT@
];

#[test]
fn rs_corrects_at_full_capacity() {
    use barcode_pdf417::rs::rs_correct;
    for &(payload, level, full, spec) in RS_CORRUPTIONS.iter() {
        let k = k_for_level(level);
        let mut bad = full.to_vec();
        for &(pos, delta) in spec {
            bad[pos] = ((bad[pos] as u32 + delta as u32) % 929) as u16;
        }
        assert!(!rs_valid(&bad, k), "{:?} must be detected corrupt", payload);
        let (fixed, fixes) = rs_correct(&bad, k)
            .unwrap_or_else(|| panic!("{:?}: correction failed", payload));
        assert_eq!(fixed, full, "{:?} corrected stream", payload);
        assert_eq!(fixes.len(), spec.len(), "{:?} fix count", payload);
        assert!(rs_valid(&fixed, k), "{:?} corrected valid", payload);
    }
}
"""

