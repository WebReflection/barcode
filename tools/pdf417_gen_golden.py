def bmp_matrix_topdown(bmp):
    """Exact module matrix from a zint BMP: 2px/module, bit 0 = dark,
    file rows bottom-up -> top-down matrix with 1 = dark."""
    w, h, get_row = raw_rows(bmp)
    mw, mh = w // 2, h // 2
    m = [[0] * mw for _ in range(mh)]
    for y in range(mh):
        bits = get_row(h - 1 - 2 * y)  # bottom-up file rows, 2px/module
        for x in range(mw):
            m[y][x] = 1 - bits[x * 2]
    return m, mh, mw


def matrix_str(matrix):
    return "\n".join("".join("#" if v == 1 else "." for v in row) for row in matrix)


def case_block(payload, m, R, C, stream):
    mstr = matrix_str(m).replace("\n", "\\n")
    return (
        "    // payload: %r  (%d rows x %d cols)\n"
        "    GoldenCase {\n"
        "        payload: %s,\n"
        "        w: %d,\n"
        "        h: %d,\n"
        "        stream: &%s,\n"
        '        matrix: "%s",\n'
        "    },"
    ) % (payload, R, C, json.dumps(payload), C, R, json.dumps(stream), mstr)


TEST_TMPL = """//! Golden PDF417 decode tests. GENERATED by tools/pdf417_gen_golden.py
//! from zint oracle renders -- do not edit by hand.
//!
//! Matrix convention: '#' = dark, '\\n'-separated rows. Streams include
//! the length descriptor; pads (900) and ECC follow the data.

use barcode_pdf417::decode_exact;
use barcode_pdf417::stream::{read_exact, split_stream, strip_pads};
use barcode_pdf417::text::decode_text;

struct GoldenCase {
    payload: &'static str,
    w: usize,
    h: usize,
    stream: &'static [u16],
    matrix: &'static str,
}

const CASES: &[GoldenCase] = &[
@BLOCKS@
];

fn dark_matrix(case: &GoldenCase) -> Vec<u8> {
    let mut v = Vec::with_capacity(case.w * case.h);
    for line in case.matrix.split("\\n") {
        assert_eq!(line.len(), case.w, "{:?} line width", case.payload);
        for ch in line.chars() {
            v.push(if ch == '#' { 1 } else { 0 });
        }
    }
    assert_eq!(v.len(), case.w * case.h);
    v
}

#[test]
fn golden_streams() {
    for case in CASES {
        let dark = dark_matrix(case);
        let stream = read_exact(&dark, case.w, case.h)
            .unwrap_or_else(|| panic!("{:?}: no stream", case.payload));
        assert_eq!(stream, case.stream, "{:?} stream", case.payload);
    }
}

#[test]
fn golden_text() {
    for case in CASES {
        let dark = dark_matrix(case);
        let text = decode_exact(&dark, case.w, case.h)
            .unwrap_or_else(|| panic!("{:?}: no text", case.payload));
        assert_eq!(text, case.payload.as_bytes(), "{:?} text", case.payload);
    }
}

#[test]
fn golden_descriptor_counts_data_and_pads() {
    for case in CASES {
        let dark = dark_matrix(case);
        let stream = read_exact(&dark, case.w, case.h).unwrap();
        let (desc, data_pads, _ecc) = split_stream(&stream).unwrap();
        assert_eq!(desc as usize, 1 + data_pads.len(), "{:?}", case.payload);
        let text = decode_text(strip_pads(data_pads)).unwrap();
        assert_eq!(text, case.payload, "{:?}", case.payload);
    }
}
"""


