def gen_detect():
    """Padded noisy canvases validated by the Python detector."""
    import pdf417_detect_probe as D
    import random
    vectors = []
    for ci, payload in [(0, "A1"), (2, "MiXeD 42!"),
                        (3, "The quick brown fox jumps over the lazy dog 123 times!")]:
        m = D.render(payload, level=0)  # same geometry as the CASES matrices
        for qz, up, noise, seed in [(8, 2, 0, 1), (8, 2, 100, 2), (8, 3, 200, 3),
                                    (12, 2, 200, 4), (8, 4, 400, 5)]:
            canvas = D.paste(m, qz=qz, noise_px=0, upscale=up)
            H, W = len(canvas), len(canvas[0])
            rng = random.Random(seed)
            flips = []
            for _ in range(noise):
                flips.append((rng.randrange(W), rng.randrange(H)))
            for x, y in flips:
                canvas[y][x] ^= 1
            got = D.detect(canvas)
            if got == (payload if isinstance(payload, bytes) else payload.encode()):
                vectors.append((ci, qz, up, W, H, flips))
    return vectors


def gen():
    blocks = []
    for payload in CASES:
        z = zint.Zint(payload, zint.BARCODE_PDF417, scale=1, show_text=False,
                      border_width=0, whitespace_width=0, option_1=0)
        m, R, C = bmp_matrix_topdown(z.render_bmp())
        stream = data_stream(payload)
        split_stream(stream)  # sanity
        blocks.append(case_block(payload, m, R, C, stream))

    rvec = []
    for payload, level in RS_CASES:
        stream = data_stream(payload, ecc=level)
        desc = stream[0]
        message, ecc = stream[:desc], stream[desc:]
        assert len(ecc) == k_for_level(level), (payload, level, len(ecc))
        rvec.append("    (%s, %d, &%s, &%s)," % (
            json.dumps(payload), level, json.dumps(message), json.dumps(ecc)))

    rcorr = []
    for i, (payload, level) in enumerate(RS_CORRUPT):
        stream = data_stream(payload, ecc=level)
        k = k_for_level(level)
        cap = (k - 2) // 2
        spec = corrupt_specs(stream, k, cap, seed=1000 + i)
        rcorr.append("    (%s, %d, &%s, &[%s])," % (
            json.dumps(payload), level, json.dumps(stream),
            ", ".join("(%d, %d)" % p for p in spec)))

    out = TEST_TMPL.replace("@BLOCKS@", "\n".join(blocks))
    body = RS_TMPL.replace("@RVECTORS@", "\n".join(rvec))
    body = body.replace("@RCORRUPT@", "\n".join(rcorr))
    mvec = []
    for payload, level in MODE_CASES:
        stream = data_stream(payload, ecc=level)
        desc = stream[0]
        end = desc
        while end > 1 and stream[end - 1] == 900:
            end -= 1  # strip trailing 900 pads
        mvec.append("    (&%s, &%s)," % (json.dumps(list(payload)), json.dumps(stream[1:end])))

    dvec = []
    for ci, qz, up, W, H, flips in gen_detect():
        dvec.append("    (%d, %d, %d, %d, %d, &[%s])," % (
            ci, qz, up, W, H, ", ".join("(%d,%d)" % f for f in flips)))

    open(OUT, "w").write(out + body + "\n" +
                         MODE_TMPL.replace("@MVECTORS@", "\n".join(mvec)) + "\n" +
                         DETECT_TMPL.replace("@DVECTORS@", "\n".join(dvec)))
    print("wrote", OUT)


if __name__ == "__main__":
    gen()
