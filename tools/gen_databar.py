#!/usr/bin/env python3
"""Generate the GS1 DataBar Omnidirectional tables + verify bit-exact vs zint.

Pipeline (microqr-gen pattern):
  1. Load /tmp/opencode/dbar/tables.json (oracle sweeps from the probe session).
  2. Rebuild the full 46-run symbol in Python for a verification set
     (chain split -> segment tables -> finder rule) and compare with fresh
     zint renders, bit-exact, via tools/databar_probe.widths().
  3. Only on a clean verification, emit:
       crates/barcode-databar/src/tables.rs        (decoder tables)
       crates/barcode-fixtures/src/databar_tables.rs (encoder tables)

Run: /tmp/opencode/zxenv/bin/python tools/gen_databar.py
"""
import json
import random
import sys

sys.path.insert(0, "/Users/ag/git/barcode/tools")
import databar_probe as dp  # noqa: E402

REPO = "/Users/ag/git/barcode"
TABLES_JSON = "/tmp/opencode/dbar/tables.json"

# ISO/IEC 24724 Table 4, values 0..8 -> first three elements (s,b,s).
T4 = [[3, 8, 2], [3, 5, 5], [3, 3, 7], [3, 1, 9],
      [2, 7, 4], [2, 5, 6], [2, 3, 8], [1, 5, 7], [1, 3, 9]]


def as_list(d, n):
    out = [None] * n
    for k, w in d.items():
        out[int(k)] = list(w)
    assert all(w is not None for w in out), "table has gaps"
    return out


def load_tables():
    """tables.json keys are the PINNED RENDER VALUES (V = residue × radix);
    map them back to residues: R2 = V//1597, R3 = V//4537077, R4 = V//7245711969."""
    t = json.load(open(TABLES_JSON))
    s2 = [None] * 2841
    for k, w in t["S2"].items():
        s2[int(k) // 1597] = list(w)
    p2 = [None] * 1597
    for k, w in t["pair2"].items():
        p2[int(k) // 4_537_077] = list(w)
    s1 = [None] * 1381
    for k, w in t["S1"].items():
        s1[int(k) // 7_245_711_969] = list(w)
    p3 = [None] * 1597
    for k, w in t["pair3"].items():
        p3[int(k)] = list(w)  # pinned V = R1 directly
    assert all(x is not None for x in s1 + p2 + p3 + s2), "table has gaps"
    return s1, p2, p3, s2


def build_runs(v, S1, P2, P3, S2):
    """Full 46-run symbol for 13-digit value v. Windows (0-based):
    S1 = runs 1-9 (table 9-wide incl. bar), pair2 = 15-22, pair3 = 23-30,
    S2 = 36-45 (table 10-wide incl. space + final bar).
    Finder checksum elements: S1 pair L→R, pair2 R→L, S2 pair R→L,
    pair3 L→R (each group read toward its adjacent finder)."""
    r1 = v % 1597
    r2 = (v // 1597) % 2841
    r3 = (v // 4_537_077) % 1597
    r4 = v // 7_245_711_969
    runs = [0] * 46
    runs[0] = 1
    runs[1:10] = S1[r4]
    runs[15:23] = P2[r3]
    runs[23:31] = P3[r1]
    runs[36:46] = S2[r2]
    # Finder checksum windows (verified 5007/5007 vs zint, probeFinder10.py):
    # char1 = runs 2..9, char2 = 22..15, char4 = 43..36, char3 = 23..30.
    # Note these cross the segment boundaries above — per ISO 24724 the
    # checksum's characters are not the same groups as the value chain's.
    e = (list(runs[2:10]) + list(runs[22:14:-1])
         + list(runs[43:35:-1]) + list(runs[23:31]))
    c = sum(3 ** k * e[k] for k in range(32)) % 79
    raw = c + (1 if c >= 8 else 0) + (1 if c >= 72 else 0)
    cl, cr = divmod(raw, 9)
    runs[10:13] = T4[cl]
    runs[13] = 1
    runs[14] = 1
    runs[31] = 1
    runs[32] = 1
    runs[33:36] = [T4[cr][2], T4[cr][1], T4[cr][0]]
    return runs


def verification_values():
    random.seed(20261020)
    vals = [0, 1, 9_999_999_999_999, 4_537_077, 7_245_711_969,
            9_999_082_517_220,  # R4 = 1380 exactly
            9_999_082_517_219, 10_000_000_000_000 - 1]
    vals += [random.randrange(10_000_000_000_000) for _ in range(300)]
    return vals


def verify(S1, P2, P3, S2):
    bad = 0
    for v in verification_values():
        mine = build_runs(v, S1, P2, P3, S2)
        oracle = list(dp.widths(f"{v:013d}"))
        if mine != oracle:
            bad += 1
            if bad <= 3:
                print(f"MISMATCH v={v}")
                print("  mine  :", mine)
                print("  oracle:", oracle)
                print("  diff  :", [i for i, (a, b) in enumerate(zip(mine, oracle)) if a != b])
    return bad


def emit_rust(name, doc, rows):
    """rows: list of int-lists -> `pub static NAME: [[u8; W]; N]`."""
    w = len(rows[0])
    body = ",\n".join("    [" + ",".join(str(x) for x in r) + "]" for r in rows)
    return f"// {doc}\n// Generated by tools/gen_databar.py from oracle sweeps — do not edit by hand.\npub static {name}: [[u8; {w}]; {len(rows)}] = [\n{body},\n];\n"


def pack_key(row, skip=0):
    """Eight module widths (1..=8) -> one u32, most-significant nibble first.
    The decoder looks keys up by binary search, so this must stay in sync
    with `barcode-databar`'s `sorted_index`."""
    x = 0
    for v in row[skip:skip + 8]:
        assert 1 <= v <= 15, v
        x = (x << 4) | v
    return x


def emit_index(name, doc, rows, skip=0):
    """rows: list of int-lists -> `NAME_KEYS` (sorted u32) + `NAME_INDEX`
    (the row's residue, aligned with the sorted keys). The decoder only
    needs pattern -> residue, so it does not ship the width rows."""
    pairs = sorted((pack_key(r, skip), i) for i, r in enumerate(rows))
    keys = ",\n".join(
        "    " + ", ".join(f"{k}" for k, _ in pairs[i:i + 8])
        for i in range(0, len(pairs), 8))
    idx = ",\n".join(
        "    " + ", ".join(f"{v}" for _, v in pairs[i:i + 12])
        for i in range(0, len(pairs), 12))
    return (f"// {doc}\n"
            f"// Generated by tools/gen_databar.py from oracle sweeps — do not edit by hand.\n"
            f"// Sorted by packed pattern for binary search; INDEX holds the residue.\n"
            f"pub static {name}_KEYS: [u32; {len(pairs)}] = [\n{keys},\n];\n"
            f"pub static {name}_INDEX: [u16; {len(pairs)}] = [\n{idx},\n];\n")


def main():
    S1, P2, P3, S2 = load_tables()
    print("verifying against zint …")
    bad = verify(S1, P2, P3, S2)
    if bad:
        print(f"FAILED: {bad} mismatches — not emitting")
        sys.exit(1)
    print("all verification values bit-exact vs zint ✓")

    header = "// eslint-disable-next-line\n"
    # Decoder: pattern -> residue index tables (binary-searchable). The
    # width rows themselves are only needed by the encoder.
    dec = []
    dec.append(emit_index("S1", "S1 segment: R4 (0..1380) -> runs 1-9", S1))
    dec.append(emit_index("PAIR2", "pair2 segment: R3 (0..1596) -> runs 15-22", P2))
    dec.append(emit_index("PAIR3", "pair3 segment: R1 (0..1596) -> runs 23-30", P3))
    dec.append(emit_index("S2", "S2 segment: R2 (0..2840) -> runs 36-45", S2, skip=1))
    dec.append(emit_rust("FINDER_T4", "ISO 24724 Table 4 values 0..8 (first 3 elements)", T4))
    tables_body = ("//! Oracle-extracted GS1 DataBar Omnidirectional segment tables.\n\n"
                   + header.join(dec))
    open(f"{REPO}/crates/barcode-databar/src/tables.rs", "w").write(tables_body)
    # Fixtures keeps the width rows for the encoder (independent
    # transcription policy: the generator guarantees the two copies agree;
    # the crates share no code).
    enc = []
    enc.append(emit_rust("S1", "S1 segment: R4 (0..1380) -> runs 1-9", S1))
    enc.append(emit_rust("PAIR2", "pair2 segment: R3 (0..1596) -> runs 15-22", P2))
    enc.append(emit_rust("PAIR3", "pair3 segment: R1 (0..1596) -> runs 23-30", P3))
    enc.append(emit_rust("S2", "S2 segment: R2 (0..2840) -> runs 36-45", S2))
    enc.append(emit_rust("FINDER_T4", "ISO 24724 Table 4 values 0..8 (first 3 elements)", T4))
    open(f"{REPO}/crates/barcode-fixtures/src/databar_tables.rs", "w").write(
        "//! Oracle-extracted GS1 DataBar Omnidirectional segment tables.\n\n"
        + header.join(enc))
    # golden vectors: bit-exact 46-run expectations for the encoder tests
    golden = verification_values()[:64]
    with open(f"{REPO}/crates/barcode-fixtures/tests/databar_golden.txt", "w") as f:
        for v in golden:
            f.write(f"{v}:" + ",".join(str(x) for x in build_runs(v, S1, P2, P3, S2)) + "\n")
    print("emitted tables.rs + fixtures tables + 64 golden vectors")


if __name__ == "__main__":
    main()
