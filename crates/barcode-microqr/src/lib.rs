//! Clean-room Micro QR Code encoder (versions M1–M3).
//!
//! Reconstructed empirically against an oracle renderer (see
//! `docs/STATUS.md` and `PROVENANCE.md`; no third-party decoder source
//! was consulted). Coverage:
//!
//! | version | size  | levels | numeric | alnum | byte |
//! |---------|-------|--------|---------|-------|------|
//! | M1      | 11×11 | L      | 1–5     | —     | —    |
//! | M2      | 13×13 | L, M   | 1–10/8  | 1–6/5 | —    |
//! | M3      | 15×15 | L, M   | 1–23/18 | 1–14/11 | 1–9/7 |
//! | M4      | 17×17 | L, M, Q| see note | see note | see note |
//!
//! M4 frames are generated by the same empirical pipeline (levels L/M
//! numeric + alnum verified; byte and Q tiers partially verified —
//! see `docs/STATUS.md`).
//!
//! # Frame model
//!
//! Each (version, level, mode, length) has an empirical frame: a data-cell
//! list, a fill list (cells unused by that frame but used by others of the
//! same version), a bit matrix `G` over the payload field bits, and one
//! constant `K` per mask class. The symbol is
//! `template ⊕ fill`, then `data cell = (G·f mod 2) ⊕ K_c`.
//!
//! Numeric fields: 3-digit groups as 10 bits while ≥3 digits remain, then
//! a 2-digit tail (7 bits) or 1-digit tail (4 bits). Alnum: pairs as
//! `idx1*45 + idx2` in 11 bits (QR 45-char alphabet), odd tail 6 bits.
//! Byte: one 8-bit field per byte. M1 writes fields MSB-first; M2/M3 in
//! exponent order (the physical write order these imply is captured by G).
//!
//! Mask classes are empirical per frame; `class: None` picks class 0.
//! Payloads that the oracle would re-mode (all-digit "alnum", 3+ digit
//! runs, all-alnum "byte") are rejected to keep the frame valid.
//!
//! # Example
//!
//! ```
//! use barcode_microqr::{encode, Level, Version};
//!
//! let sym = encode("12345", Version::M1, Level::L, None).unwrap();
//! assert_eq!(sym.size, 11);
//! assert!(sym.ink(0, 0));
//! ```

pub mod decoder;
pub mod frames;

pub use decoder::{decode, decode as decode_microqr};

/// Micro QR version (size and capacity tier).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Version {
    M1,
    M2,
    M3,
    M4,
}

/// Error correction level. Availability depends on the version.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Level {
    L,
    M,
    Q,
}

/// Encoding mode.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Numeric,
    Alnum,
    Byte,
}

impl Mode {
    fn code(self) -> u8 {
        match self {
            Mode::Numeric => 0,
            Mode::Alnum => 1,
            Mode::Byte => 2,
        }
    }
}

/// A rendered Micro QR symbol: a square row-major 0/1 module matrix.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Symbol {
    /// Side length in modules.
    pub size: usize,
    /// Row-major module values, `size * size` entries, 1 = inked.
    pub cells: Vec<u8>,
}

impl Symbol {
    /// Module value at (x, y); `false` outside the symbol.
    pub fn ink(&self, x: usize, y: usize) -> bool {
        x < self.size && y < self.size && self.cells[y * self.size + x] == 1
    }
}

const ALNUM: &[u8; 45] = b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ $%*+-./:";

/// Content-based mode detection, mirroring the oracle: all ASCII digits
/// map to numeric, the 45-char alphanumeric set to alnum, else byte.
pub fn detect(payload: &[u8]) -> Mode {
    if !payload.is_empty() && payload.iter().all(|b| b.is_ascii_digit()) {
        return Mode::Numeric;
    }
    if payload.iter().all(|b| ALNUM.contains(b)) {
        return Mode::Alnum;
    }
    Mode::Byte
}

/// Split a numeric payload into (digit-count, bit-width) fields.
pub fn fields(len: usize, mode: Mode) -> Vec<(usize, usize)> {
    match mode {
        Mode::Byte => vec![(1, 8); len],
        Mode::Alnum => {
            let mut f = vec![(2, 11); len / 2];
            if len % 2 == 1 {
                f.push((1, 6));
            }
            f
        }
        Mode::Numeric => {
            let mut rem = len;
            let mut f = Vec::new();
            while rem >= 3 {
                f.push((3, 10));
                rem -= 3;
            }
            match rem {
                2 => f.push((2, 7)),
                1 => f.push((1, 4)),
                _ => {}
            }
            f
        }
    }
}

/// Field bit vector from per-field values. M1 writes each field
/// MSB-first; M2/M3 in exponent order.
fn model_f(frame: &frames::Frame, vals: &[u32]) -> Vec<u8> {
    let f = field_widths(frame);
    let mut out = Vec::with_capacity(frame.cols);
    for (idx, &(_, width)) in f.iter().enumerate() {
        let v = vals[idx];
        if frame.msb_first {
            for j in 0..width {
                out.push(((v >> (width - 1 - j)) & 1) as u8);
            }
        } else {
            for e in 0..width {
                out.push(((v >> e) & 1) as u8);
            }
        }
    }
    out
}

/// Per-field (char count, bit width) for a frame, from its mode/length.
fn field_widths(frame: &frames::Frame) -> Vec<(usize, usize)> {
    let mode = match frame.mode {
        0 => Mode::Numeric,
        1 => Mode::Alnum,
        _ => Mode::Byte,
    };
    fields(frame.len as usize, mode)
}

/// Encode a text payload with automatic mode detection.
///
/// `class` selects the mask class; `None` picks class 0. Returns `None`
/// for payloads outside the version/level/mode capacity.
pub fn encode(
    payload: &str,
    version: Version,
    level: Level,
    class: Option<usize>,
) -> Option<Symbol> {
    encode_bytes(payload.as_bytes(), version, level, None, class)
}

/// Encode a payload with an explicit mode (or `None` to auto-detect).
///
/// Byte payloads should be raw bytes; text is UTF-8 encoded by the
/// caller when relevant.
pub fn encode_bytes(
    payload: &[u8],
    version: Version,
    level: Level,
    mode: Option<Mode>,
    class: Option<usize>,
) -> Option<Symbol> {
    let (v, lv) = match (version, level) {
        (Version::M1, Level::L) => (1, 1),
        (Version::M2, Level::L) => (2, 1),
        (Version::M2, Level::M) => (2, 2),
        (Version::M3, Level::L) => (3, 1),
        (Version::M3, Level::M) => (3, 2),
        (Version::M4, Level::L) => (4, 1),
        (Version::M4, Level::M) => (4, 2),
        (Version::M4, Level::Q) => (4, 3),
        // M1 has no level-M/Q tiers; M2/M3 have no Q tier
        (Version::M1, _) => return None,
        (Version::M2 | Version::M3, Level::Q) => return None,
    };
    let mode = mode.unwrap_or_else(|| detect(payload));
    // guard against payloads the oracle would re-mode
    match mode {
        Mode::Numeric => {
            if !payload.iter().all(|b| b.is_ascii_digit()) {
                return None;
            }
        }
        Mode::Alnum => {
            if !payload.iter().all(|b| ALNUM.contains(b)) {
                return None;
            }
            if payload.iter().all(|b| b.is_ascii_digit()) {
                return None; // would encode as numeric
            }
            if payload.windows(3).any(|w| w.iter().all(|b| b.is_ascii_digit())) {
                return None; // 3+ digit run: oracle segments numerically
            }
        }
        Mode::Byte => {
            if payload.iter().all(|b| ALNUM.contains(b)) {
                return None; // would encode as numeric/alnum
            }
        }
    }
    let len = payload.len();
    let (_, frame) = frames::FRAMES.iter().find(|(k, _)| k[0] == v && k[1] == lv && k[2] == mode.code() && k[3] == len as u8)?;

    // per-field values
    let fw = field_widths(frame);
    let mut vals = Vec::with_capacity(fw.len());
    let mut off = 0usize;
    for &(n, _) in &fw {
        let mut v: u32 = 0;
        match mode {
            Mode::Numeric => {
                for i in 0..n {
                    v = v * 10 + (payload[off + i] - b'0') as u32;
                }
            }
            Mode::Alnum => {
                if n == 2 {
                    let a = ALNUM.iter().position(|c| *c == payload[off])? as u32;
                    let b = ALNUM.iter().position(|c| *c == payload[off + 1])? as u32;
                    v = a * 45 + b;
                } else {
                    v = ALNUM.iter().position(|c| *c == payload[off])? as u32;
                }
            }
            Mode::Byte => v = payload[off] as u32,
        }
        off += n;
        vals.push(v);
    }

    let f = model_f(frame, &vals);
    let ki = class.unwrap_or(0);
    let k = frame.ks.get(ki)?;
    let mut cells = frames::tmpl(v).1.to_vec();
    for &(x, y, val) in frame.fill {
        cells[y as usize * frames::tmpl(v).0 + x as usize] = val;
    }
    let n = frame.data.len();
    for (i, &(x, y)) in frame.data.iter().enumerate() {
        let mut bit = 0u32;
        for j in 0..frame.cols {
            if f[j] == 1 {
                bit ^= frame.g[i * frame.cols + j] as u32;
            }
        }
        cells[y as usize * frames::tmpl(v).0 + x as usize] = (bit ^ k[i] as u32) as u8;
    }
    let _ = n;
    Some(Symbol { size: frames::tmpl(v).0, cells })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_bad_payloads() {
        assert!(encode("", Version::M1, Level::L, None).is_none());
        assert!(encode("12a5", Version::M1, Level::L, None).is_none());
        assert!(encode("123456", Version::M1, Level::L, None).is_none());
        // all-digit alnum would re-mode
        assert!(encode_bytes(b"12", Version::M2, Level::L, Some(Mode::Alnum), None).is_none());
        // class out of range
        assert!(encode("12345", Version::M1, Level::L, Some(99)).is_none());
    }

    #[test]
    fn sizes_and_finder() {
        let s = encode("42", Version::M1, Level::L, None).unwrap();
        assert_eq!(s.size, 11);
        assert!(s.ink(0, 0) && s.ink(6, 0) && s.ink(0, 6));
        let s = encode("1234567890", Version::M2, Level::L, None).unwrap();
        assert_eq!(s.size, 13);
        let s = encode("12345678901234567890123", Version::M3, Level::L, None).unwrap();
        assert_eq!(s.size, 15);
    }

    #[test]
    fn modes_detect() {
        assert_eq!(detect(b"123"), Mode::Numeric);
        assert_eq!(detect(b"A1"), Mode::Alnum);
        assert_eq!(detect(b"\x00"), Mode::Byte);
    }
}
