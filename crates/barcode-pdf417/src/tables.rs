/// Look up the value of an 8-element pattern within one cluster
/// (linear scan; rows are short and the table fits in cache).
pub fn value_of(cluster: usize, pattern: &[u8]) -> Option<u16> {
    let table = match cluster {
        0 => &CLUSTER_0,
        3 => &CLUSTER_3,
        6 => &CLUSTER_6,
        _ => return None,
    };
    if pattern.len() != 8 {
        return None;
    }
    table.iter().position(|p| p == pattern).map(|v| v as u16)
}

/// Cluster of row  (1-based).
pub fn cluster_of_row(row: usize) -> usize {
    ((row - 1) % 3) * 3
}

